"""Recently seen screens: a runtime observation, held in memory only (ADR-0007).

Each `/api/board` request notes the browser's User-Agent, the Display profile it
was given and how that was chosen. The Admin lists them so the operator can copy
a User-Agent token from a real screen. This is neither Settings nor Status: it is
not regenerated by any job, so it is never written to disk and is lost on
restart. Bounded, so a scanner cannot grow it.
"""
from __future__ import annotations

import threading
import time
from typing import NamedTuple

MAX_SEEN_SCREENS = 50
_MAX_USER_AGENT_LEN = 300     # longest User-Agent remembered


class SeenScreen(NamedTuple):
    user_agent: str
    profile: str      # the profile the screen got ("default" for the Default profile)
    chosen: str       # how: a `config_store.CHOSEN_*` value
    last_seen: float  # epoch seconds


_seen: dict[tuple[str, str, str], float] = {}
_lock = threading.Lock()


def record_seen_screen(user_agent: str | None, profile: str, chosen: str,
                       now: float | None = None) -> None:
    """Remember that a screen with this User-Agent got this profile this way.

    One entry per (User-Agent, profile, how), so a screen whose assignment changes
    shows both the old and the new outcome; the one seen again moves to most recent.
    """
    ua = " ".join(str(user_agent or "").split())[:_MAX_USER_AGENT_LEN] or "(none sent)"
    key = (ua, profile, chosen)
    with _lock:
        _seen.pop(key, None)
        _seen[key] = time.time() if now is None else now
        while len(_seen) > MAX_SEEN_SCREENS:
            _seen.pop(next(iter(_seen)))


def seen_screens() -> list[SeenScreen]:
    """Recently seen screens since the last restart, most recent first."""
    with _lock:
        return [SeenScreen(*key, ts) for key, ts in reversed(_seen.items())]


def clear_seen_screens() -> None:
    """Forget every seen screen (tests)."""
    with _lock:
        _seen.clear()
